export const missing = new Map();
function tr(text, where) {
  if (!CJK.test(text)) return text;
  const lead = text.match(/^\s*/)[0],
    trail = text.match(/\s*$/)[0];
  const key = text.trim();
  let t = D[key];
  if (t === undefined) {
    t = key;
    for (const [re, rep] of PATTERNS)
      if (re.test(t)) {
        t = t.replace(re, rep);
        break;
      }
  }
  if (CJK.test(t) && t !== '中') missing.set(key, where);
  return lead + t + trail;
}
export const enTitle = (s) => tr(s, 'title');
export function toEnglish(html, where = '') {
  for (const [a, b] of [...RAW, ...(RAW_BOARD[where] ?? [])]) html = html.split(a).join(b);
  const parts = html.split(/(<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>)/);
  return parts
    .map((p, i) =>
      i % 2
        ? p
        : p
            .replace(/>([^<>]+)</g, (all, text) => '>' + tr(text, where) + '<')
            .replace(
              /(\s(?:aria-label|title|placeholder|alt|value)=")([^"]*)"/g,
              (all, pre, v) => pre + tr(v, where) + '"',
            ),
    )
    .join('');
}
